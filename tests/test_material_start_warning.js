const fs = require('node:fs');
const assert = require('node:assert/strict');
const {JSDOM} = require('jsdom');
const {jQueryFactory} = require('jquery/factory');
(async function () {
    const dom = new JSDOM('<div id="state"><div class="progress"></div></div>', {runScripts:'outside-only'});
    const w = dom.window, $ = jQueryFactory(w);
    w.$ = w.jQuery = $;
    w.eval(fs.readFileSync(require.resolve('knockout/build/output/knockout-latest.js'), 'utf8'));
    w.OCTOPRINT_VIEWMODELS = []; w.gettext = x => x;
    const notices = [];
    w.PNotify = function (options) { this.options=options; this.remove=()=>{this.removed=true;}; notices.push(this); };
    w.eval(fs.readFileSync('octoprint_rme_compatibility/static/js/rme_compatibility.js','utf8'));
    await new Promise(resolve=>$(resolve));
    const ko=w.ko, native={continuousPrintStateString:ko.observable('SpoolManager: not enough filament left for T1 (Black ASA)'),
        continuousPrintStateStatus:ko.observable('NEEDS_ACTION')};
    const vm=new w.OCTOPRINT_VIEWMODELS[0].construct([{settings:{plugins:{rme_compatibility:{}}}}, {}, native, {}]);
    vm.acceptState({connected:true,supported:true}); vm.onAllBound();
    assert.equal(notices.length,1,'an already-blocked queue warns on page load');
    assert.match($('#rme-material-start-warning').text(),/T1 \(Black ASA\)/);
    assert.match($('#rme-material-start-warning').text(),/remaining filament/);
    assert.equal(notices[0].options.hide,false);
    assert.equal(notices[0].options.text_escape,true);
    vm.onAllBound(); vm.acceptState({connected:true,supported:true});
    assert.equal(notices.length,1,'no repeated warning for polls or duplicate binding');
    const message = status => vm.onDataUpdaterPluginMessage('continuousprint',{type:'setstate',state:JSON.stringify({status,statusType:'NEEDS_ACTION'})});
    message('SpoolManager: not enough filament left for T2 (<img src=x onerror=bad()>)');
    assert.equal($('#rme-material-start-warning img').length,0,'spool names are text, never HTML');
    assert.equal(notices.length,2); assert.equal(notices[0].removed,true);
    const before=$('#rme-material-start-warning').text();
    vm.onDataUpdaterPluginMessage('continuousprint',{type:'setstate',state:'invalid json'});
    assert.equal($('#rme-material-start-warning').text(),before);
    vm.onDataUpdaterPluginMessage('continuousprint',{type:'setstate',state:JSON.stringify({status:'Printing',statusType:'NORMAL'})});
    assert.equal($('#rme-material-start-warning')[0].style.display,'none');
    assert.equal(notices[1].removed,true);
    native.continuousPrintStateString('SpoolManager: missing metadata or spool fields');
    assert.match($('#rme-material-start-warning').text(),/missing metadata/);
    vm.acceptState({connected:false,supported:true});
    assert.equal($('#rme-material-start-warning')[0].style.display,'none');
    w.close(); console.log('ContinuousPrint material blocks show persistent, escaped, deduplicated and clearable warnings');
})().catch(error=>{console.error(error);process.exitCode=1;});
