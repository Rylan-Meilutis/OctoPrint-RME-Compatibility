const fs = require('node:fs');
const assert = require('node:assert/strict');
const {JSDOM} = require('jsdom');
const {jQueryFactory} = require('jquery/factory');
(async function () {
    const dom = new JSDOM('<html><body><div id="tab_plugin_dashboard"><div class="dashboardGridContainer"><div id="fan" class="dashboard_threeQuarterGauge" data-bind="css: gaugesCentreInGrid(\'fan\')"><svg style="width:140px;height:140px" viewBox="0 0 140 140"><path class="dashboardGauge" d="native-arc" stroke-dasharray="250" /></svg></div></div><p id="existing">Dashboard remains intact</p></div></body></html>', {runScripts: 'outside-only'});
    const w = dom.window, $ = jQueryFactory(w);
    w.$ = w.jQuery = $;
    w.eval(fs.readFileSync(require.resolve('knockout/build/output/knockout-latest.js'), 'utf8'));
    w.OCTOPRINT_VIEWMODELS = []; w.gettext = x => x; w.PNotify = function () {};
    w.eval(fs.readFileSync('octoprint_rme_compatibility/static/js/rme_compatibility.js', 'utf8'));
    await new Promise(resolve => $(resolve));
    const vm = new w.OCTOPRINT_VIEWMODELS[0].construct([{}, {}, {}, {}]);
    vm.state({supported: true, connected: true, tool_changes: {active: true, file: 'a.gcode', remaining: 3, total: 9}});
    vm.renderToolChangeWidget(); vm.renderToolChangeWidget();
    assert.equal(w.document.querySelectorAll('#rme-tool-changes-dashboard').length, 1);
    assert.equal($('#rme-tool-changes-dashboard .rme-tool-changes-value').text(), '3/9');
    assert.equal($('#rme-tool-changes-dashboard').parent().hasClass('dashboardGridContainer'), true);
    assert.equal($('#rme-tool-changes-dashboard path').first().attr('d'), 'native-arc');
    assert.equal($('#rme-tool-changes-dashboard > svg').css('height'), '140px');
    assert(Math.abs(Number($('#rme-tool-changes-dashboard .rme-tool-changes-gauge').attr('stroke-dashoffset')) - 250 * 2 / 3) < 0.001);
    assert.equal(w.document.querySelector('#existing').textContent, 'Dashboard remains intact');
    vm.state({supported: true, connected: true, tool_changes: {active: true, file: 'a.gcode', remaining: 0, total: 9}});
    assert.equal($('#rme-tool-changes-dashboard .rme-tool-changes-value').text(), '0/9');
    assert.equal(Number($('#rme-tool-changes-dashboard .rme-tool-changes-gauge').attr('stroke-dashoffset')), 250);
    vm.state({supported: true, connected: true, tool_changes: {active: true, file: 'a.gcode', remaining: 0, total: 0}});
    assert.equal($('#rme-tool-changes-dashboard .rme-tool-changes-value').text(), '0/0');
    assert.equal(Number($('#rme-tool-changes-dashboard .rme-tool-changes-gauge').attr('stroke-dashoffset')), 0);
    vm.state({supported: true, connected: true, tool_changes: {active: true, file: 'a.gcode', remaining: null, total: null}});
    assert.equal(vm.toolChangeText(), 'Calculating…');
    assert.equal($('#rme-tool-changes-dashboard .rme-tool-changes-value').text(), '—');
    vm.objectProgress({file: 'b.gcode', active: true, position: 0});
    assert.equal(vm.toolChangeText(), 'No active local print');
    vm.state({supported: true, connected: false});
    assert.equal($('#rme-tool-changes-dashboard').length, 0);
    vm.state({supported: true, connected: true, tool_changes: {active: true, file: 'b.gcode', remaining: 2, total: 2}});
    assert.equal($('#rme-tool-changes-dashboard .rme-tool-changes-value').text(), '2/2');
    assert.equal(Number($('#rme-tool-changes-dashboard .rme-tool-changes-gauge').attr('stroke-dashoffset')), 0);
    console.log('Dashboard planned tool-change counter passed');
    w.close();
})().catch(error => {console.error(error); process.exitCode = 1;});
