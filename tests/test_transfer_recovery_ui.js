const fs = require('node:fs');
const assert = require('node:assert/strict');
const {JSDOM} = require('jsdom');
const {jQueryFactory} = require('jquery/factory');
(async function () {
    const dom = new JSDOM('<body><div id="workspace"></div></body>', {runScripts: 'outside-only'});
    const w = dom.window, $ = jQueryFactory(w);
    w.$ = w.jQuery = $;
    w.eval(fs.readFileSync(require.resolve('knockout/build/output/knockout-latest.js'), 'utf8'));
    w.OCTOPRINT_VIEWMODELS = [];
    w.gettext = x => x;
    w.PNotify = function () {};
    w.confirm = () => true;
    $.fn.modal = $.fn.tab = function () { return this; };
    w.eval(fs.readFileSync('octoprint_rme_compatibility/static/js/rme_compatibility.js', 'utf8'));
    await new Promise(resolve => $(resolve));
    const ko = w.ko;
    const vm = new w.OCTOPRINT_VIEWMODELS[0].construct([{}, {}, {}, {}]);
    vm.settings.settings = {plugins: {rme_compatibility: {firmware_variant: ko.observable('')}}};
    const commands = [];
    vm.command = command => { commands.push(command); return $.Deferred().resolve().promise(); };
    const render = name => fs.readFileSync('octoprint_rme_compatibility/templates/' + name, 'utf8')
        .replace(/{% include "([^"]+)" %}/g, (_, include) => render(include));
    const host = w.document.getElementById('workspace');
    host.innerHTML = render('rme_compatibility_tab.jinja2');
    ko.applyBindings(vm, host);
    const settingsHost = w.document.createElement('div');
    settingsHost.innerHTML = render('rme_compatibility_settings.jinja2');
    w.document.body.append(settingsHost);
    ko.applyBindings(vm, settingsHost);
    assert(settingsHost.textContent.includes('RME saved defaults'));
    assert(!settingsHost.querySelector('.rme-storage-table'));
    const panel = host.querySelector('#rme-tab-recovery');
    const button = text => Array.from(panel.querySelectorAll('button')).find(b => b.textContent.includes(text));
    const partial = {remote_path: 'FWUPD.BBF', source_available: true, recovery_active: false};
    vm.state({connected: false, supported: false, firmware: {status: 'canceling'}, storage: {partial}});
    assert.notEqual(panel.style.display, 'none');
    button('Stop and disconnect').click();
    assert.equal(commands.at(-1), 'recover_transfer');
    assert(button('Resume upload').disabled);
    vm.state({connected: false, supported: false, firmware: {status: 'error', recovery_required: true}, storage: {partial}});
    assert(button('Resume upload').disabled);
    assert(button('Discard').disabled);
    assert.equal(button('Stop and disconnect').style.display, 'none');
    button('I rebooted').click();
    assert.equal(commands.at(-1), 'confirm_printer_reboot');
    vm.state({connected: true, supported: true, firmware: {status: 'error'}, storage: {partial}});
    assert(!button('Resume upload').disabled);
    button('Resume upload').click();
    assert.equal(commands.at(-1), 'partial_resume');
    button('Discard').click();
    assert.equal(commands.at(-1), 'partial_discard');
    vm.showRmeSection('storage');
    assert(vm.settingsStorageExpanded());
    assert(host.querySelector('#rme-tab-storage .rme-storage-table'));
    assert.equal(host.querySelectorAll('#rme-tab-recovery').length, 1);
    assert(!commands.some(c => c.includes('flash')));
    dom.window.close();
    console.log('Workspace binding and stalled-transfer recovery controls passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
